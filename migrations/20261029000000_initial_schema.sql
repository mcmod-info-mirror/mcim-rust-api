-- 以下三个集合在 MongoDB 中以 ObjectId 为主键且存在重复的业务键，接口原样返回全部文档；
-- 用自增 id 作主键并保持导入顺序（接口按 id 排序）。
CREATE TABLE modrinth_categories (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icon            text        NOT NULL,
    name            text        NOT NULL,
    project_type    text,
    header          text        NOT NULL,
    sync_at         timestamptz NOT NULL
);

CREATE TABLE modrinth_loaders (
    id      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icon    text        NOT NULL,
    name    text        NOT NULL,
    sync_at timestamptz NOT NULL
);

CREATE TABLE modrinth_loader_supported_project_types (
    loader_id       bigint  NOT NULL REFERENCES modrinth_loaders (id) ON DELETE CASCADE,
    position        integer NOT NULL,
    project_type    text    NOT NULL,
    PRIMARY KEY (loader_id, position)
);

CREATE TABLE modrinth_game_versions (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         text        NOT NULL,
    version_type    text        NOT NULL,
    date            timestamptz NOT NULL,
