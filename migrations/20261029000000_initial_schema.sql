-- MCIM 关系化表结构（由 MongoDB 文档模型迁移而来）
--
-- 约定：
-- - 每个 MongoDB 集合对应一张主表；文档内的嵌套对象 / 数组拆成子表。
-- - 数组子表以 (父键, position) 为主键，position 从 0 开始，保持原数组顺序。
-- - 可选的单个嵌套对象（links、logo、license 等）为 1:1 子表，行存在即 Some，不存在即 None。
-- - 可空数组（Option<Vec<_>>）统一按空数组存储：NULL 与 [] 不再区分。
-- - 集合之间（如 version.project_id -> project）不建外键：各集合由同步服务独立写入，允许悬空引用。
-- - 子表对父表外键均为 ON DELETE CASCADE，删除父行即删除整份文档。

-- =====================================================================
-- CurseForge
-- =====================================================================

CREATE TABLE curseforge_categories (
    id                  integer     PRIMARY KEY,
    game_id             integer     NOT NULL,
    name                text        NOT NULL,
    slug                text,
    url                 text,
    icon_url            text,
    date_modified       timestamptz NOT NULL,
    is_class            boolean,
    class_id            integer,
    parent_category_id  integer,
    display_index       integer     NOT NULL,
    sync_at             timestamptz NOT NULL
);
CREATE INDEX curseforge_categories_game_class_idx ON curseforge_categories (game_id, class_id);

-- 文件内容记录：curseforge_files（独立文件文档）与 curseforge_mods.latestFiles（模组内嵌快照）共用。
CREATE TABLE curseforge_file_records (
    record_id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id                      integer     NOT NULL,
    game_id                 integer     NOT NULL,
    mod_id                  integer     NOT NULL,
    is_available            boolean,
    display_name            text,
    file_name               text,
    release_type            integer,
    file_status             integer,
    file_date               timestamptz,
    file_length             bigint,
    download_count          bigint,
    file_size_on_disk       bigint,
    download_url            text,
    expose_as_alternative   boolean,
    parent_project_file_id  integer,
    alternate_file_id       integer,
    is_server_pack          boolean,
    server_pack_file_id     integer,
    is_early_access_content boolean,
    early_access_end_date   timestamptz,
    file_fingerprint        bigint
);
CREATE INDEX curseforge_file_records_mod_date_idx ON curseforge_file_records (mod_id, file_date DESC);
CREATE INDEX curseforge_file_records_fingerprint_idx ON curseforge_file_records (file_fingerprint);

CREATE TABLE curseforge_file_record_hashes (
    record_id   bigint  NOT NULL REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    position    integer NOT NULL,
    value       text    NOT NULL,
    algo        integer NOT NULL,
    PRIMARY KEY (record_id, position)
);

CREATE TABLE curseforge_file_record_game_versions (
    record_id       bigint  NOT NULL REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    position        integer NOT NULL,
    game_version    text    NOT NULL,
    PRIMARY KEY (record_id, position)
);

CREATE TABLE curseforge_file_record_sortable_game_versions (
    record_id                   bigint      NOT NULL REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    position                    integer     NOT NULL,
    game_version_name           text,
    game_version_padded         text,
    game_version                text,
    game_version_release_date   timestamptz,
    game_version_type_id        integer,
    PRIMARY KEY (record_id, position)
);

CREATE TABLE curseforge_file_record_dependencies (
    record_id       bigint  NOT NULL REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    position        integer NOT NULL,
    mod_id          integer NOT NULL,
    relation_type   integer,
    PRIMARY KEY (record_id, position)
);

CREATE TABLE curseforge_file_record_modules (
    record_id   bigint  NOT NULL REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    position    integer NOT NULL,
    name        text,
    fingerprint bigint,
    PRIMARY KEY (record_id, position)
);

-- curseforge_files 集合：文件内容在 curseforge_file_records，这里只保存文档主键与同步状态字段。
CREATE TABLE curseforge_files (
    id              integer     PRIMARY KEY,
    record_id       bigint      NOT NULL UNIQUE REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    sync_at         timestamptz NOT NULL,
    found           boolean,
    file_cdn_cached boolean,
    need_to_cache   boolean,
    md5             text,
    sha1            text
);

CREATE TABLE curseforge_mods (
    id                      integer     PRIMARY KEY,
    game_id                 integer,
    name                    text,
    slug                    text        NOT NULL,
    summary                 text,
    status                  integer,
    download_count          bigint,
    is_featured             boolean,
    primary_category_id     integer,
    class_id                integer,
    main_file_id            integer,
    date_created            timestamptz,
    date_modified           timestamptz,
    date_released           timestamptz,
    allow_mod_distribution  boolean,
    game_popularity_rank    integer,
    is_available            boolean,
    thumbs_up_count         integer,
    rating                  integer,
    translated_summary      text,
    sync_at                 timestamptz NOT NULL,
    checked_at              timestamptz
);

CREATE TABLE curseforge_mod_links (
    mod_id      integer PRIMARY KEY REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    website_url text,
    wiki_url    text,
    issues_url  text,
    source_url  text
);

CREATE TABLE curseforge_mod_logos (
    mod_id          integer PRIMARY KEY REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    id              integer NOT NULL,
    logo_mod_id     integer NOT NULL,
    title           text,
    description     text,
    thumbnail_url   text,
    url             text
);

CREATE TABLE curseforge_mod_categories (
    mod_id              integer     NOT NULL REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    position            integer     NOT NULL,
    id                  integer,
    game_id             integer,
    name                text,
    slug                text,
    url                 text,
    icon_url            text,
    date_modified       timestamptz,
    is_class            boolean,
    class_id            integer,
    parent_category_id  integer,
    display_index       integer,
    PRIMARY KEY (mod_id, position)
);

CREATE TABLE curseforge_mod_authors (
    mod_id      integer NOT NULL REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    position    integer NOT NULL,
    id          integer NOT NULL,
    name        text    NOT NULL,
    url         text,
    PRIMARY KEY (mod_id, position)
);

CREATE TABLE curseforge_mod_screenshots (
    mod_id              integer NOT NULL REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    position            integer NOT NULL,
    id                  integer NOT NULL,
    screenshot_mod_id   integer NOT NULL,
    title               text,
    description         text,
    thumbnail_url       text,
    url                 text,
    PRIMARY KEY (mod_id, position)
);

CREATE TABLE curseforge_mod_latest_files (
    mod_id      integer NOT NULL REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    position    integer NOT NULL,
    record_id   bigint  NOT NULL UNIQUE REFERENCES curseforge_file_records (record_id) ON DELETE CASCADE,
    PRIMARY KEY (mod_id, position)
);

CREATE TABLE curseforge_mod_latest_files_indexes (
    mod_id                  integer NOT NULL REFERENCES curseforge_mods (id) ON DELETE CASCADE,
    position                integer NOT NULL,
    game_version            text,
    file_id                 integer NOT NULL,
    filename                text,
    release_type            integer,
    game_version_type_id    integer,
    mod_loader              integer,
    PRIMARY KEY (mod_id, position)
);

CREATE TABLE curseforge_translated (
    mod_id          integer     PRIMARY KEY,
    translated      text,
    original        text,
    need_to_update  boolean     NOT NULL,
    translated_at   timestamptz
);

